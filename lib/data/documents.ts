import 'server-only';
import { and, desc, eq, ilike, inArray, isNull, sql } from 'drizzle-orm';
import { withUserTx, type AppTransaction } from '@/db/client';
import * as schema from '@/db/schema';
import type { CircleContext, CircleRole } from '@/lib/types/app';
import { requireCircleRole } from '@/lib/data/circle-context';
import { bumpCircleVersion } from '@/lib/live/version';
import type { CreateDocumentInput, DocumentFilterInput } from '@/lib/schemas/documents';

/** Roles allowed to grant or revoke access to restricted documents, and to see who viewed them. */
const GRANT_ROLES: CircleRole[] = ['owner', 'coordinator'];

/** Roles that can receive a restricted-document grant (owner and coordinator already see them). */
const GRANTABLE_ROLES: CircleRole[] = ['caregiver', 'care_recipient'];

const documentColumns = {
  id: schema.documents.id,
  kind: schema.documents.kind,
  title: schema.documents.title,
  mimeType: schema.documents.mimeType,
  sizeBytes: schema.documents.sizeBytes,
  reportDate: schema.documents.reportDate,
  sensitivity: schema.documents.sensitivity,
  uploadedBy: schema.documents.uploadedBy,
  uploaderName: schema.users.fullName,
  createdAt: schema.documents.createdAt,
};

/** Escapes LIKE wildcards so a search term is matched literally. */
function escapeLike(value: string): string {
  return value.replace(/[\\%_]/g, (char) => `\\${char}`);
}

/**
 * Inserts the document row after its file has been stored, then bumps the circle version.
 * The id is generated by the caller so the blob pathname can include it.
 */
export async function createDocumentRow(
  ctx: CircleContext,
  row: {
    id: string;
    input: CreateDocumentInput;
    blobPathname: string;
    mimeType: string;
    sizeBytes: number;
    checksumSha256: string;
  },
): Promise<schema.Document> {
  const [created] = await withUserTx(ctx.userId, (tx) =>
    tx
      .insert(schema.documents)
      .values({
        id: row.id,
        circleId: ctx.circleId,
        kind: row.input.kind,
        title: row.input.title,
        blobPathname: row.blobPathname,
        mimeType: row.mimeType,
        sizeBytes: row.sizeBytes,
        checksumSha256: row.checksumSha256,
        reportDate: row.input.reportDate || null,
        sensitivity: row.input.sensitivity,
        uploadedBy: ctx.userId,
      })
      .returning(),
  );

  await bumpCircleVersion(ctx.circleId);
  return created;
}

/**
 * Lists documents in the circle, optionally filtered by kind and by a title search (ILIKE).
 * Restricted documents the caller may not see are removed by RLS.
 */
export async function listDocuments(circleId: string, filter: DocumentFilterInput = {}) {
  const ctx = await requireCircleRole(circleId);

  const conditions = [eq(schema.documents.circleId, circleId), isNull(schema.documents.deletedAt)];
  if (filter.kind) {
    conditions.push(eq(schema.documents.kind, filter.kind));
  }
  if (filter.search) {
    conditions.push(ilike(schema.documents.title, `%${escapeLike(filter.search)}%`));
  }

  return withUserTx(ctx.userId, (tx) =>
    tx
      .select(documentColumns)
      .from(schema.documents)
      .innerJoin(schema.users, eq(schema.documents.uploadedBy, schema.users.id))
      .where(and(...conditions))
      .orderBy(desc(schema.documents.createdAt))
      .limit(200),
  );
}

export type DocumentListItem = Awaited<ReturnType<typeof listDocuments>>[number];

/** Members who can receive a grant for a restricted document (caregivers and care recipient). */
export async function listGrantableMembers(circleId: string) {
  const ctx = await requireCircleRole(circleId, GRANT_ROLES);

  return withUserTx(ctx.userId, (tx) =>
    tx
      .select({
        userId: schema.users.id,
        fullName: schema.users.fullName,
        role: schema.circleMembers.role,
      })
      .from(schema.circleMembers)
      .innerJoin(schema.users, eq(schema.circleMembers.userId, schema.users.id))
      .where(
        and(
          eq(schema.circleMembers.circleId, circleId),
          inArray(schema.circleMembers.role, GRANTABLE_ROLES),
        ),
      )
      .orderBy(schema.users.fullName),
  );
}

async function assertRestrictedDocument(
  tx: AppTransaction,
  circleId: string,
  documentId: string,
) {
  const [doc] = await tx
    .select({ id: schema.documents.id, sensitivity: schema.documents.sensitivity })
    .from(schema.documents)
    .where(
      and(
        eq(schema.documents.id, documentId),
        eq(schema.documents.circleId, circleId),
        isNull(schema.documents.deletedAt),
      ),
    )
    .limit(1);

  if (!doc) {
    throw new Error('Document not found.');
  }
  if (doc.sensitivity !== 'restricted') {
    throw new Error('Only restricted documents use individual access grants.');
  }
}

/** Grants named members access to a restricted document. Owner and coordinator only. */
export async function grantRestrictedAccess(
  ctx: CircleContext,
  documentId: string,
  userIds: string[],
): Promise<number> {
  if (!GRANT_ROLES.includes(ctx.role)) {
    throw new Error('Only owners and coordinators can grant access.');
  }

  const granted = await withUserTx(ctx.userId, async (tx) => {
    await assertRestrictedDocument(tx, ctx.circleId, documentId);

    const eligible = await tx
      .select({ userId: schema.circleMembers.userId })
      .from(schema.circleMembers)
      .where(
        and(
          eq(schema.circleMembers.circleId, ctx.circleId),
          inArray(schema.circleMembers.userId, userIds),
          inArray(schema.circleMembers.role, GRANTABLE_ROLES),
        ),
      );

    if (eligible.length === 0) {
      return 0;
    }

    await tx
      .insert(schema.restrictedDocumentGrants)
      .values(
        eligible.map((member) => ({
          documentId,
          userId: member.userId,
          grantedBy: ctx.userId,
        })),
      )
      .onConflictDoNothing();

    return eligible.length;
  });

  await bumpCircleVersion(ctx.circleId);
  return granted;
}

/** Removes a member's grant on a restricted document. Owner and coordinator only. */
export async function revokeRestrictedAccess(
  ctx: CircleContext,
  documentId: string,
  userId: string,
): Promise<void> {
  if (!GRANT_ROLES.includes(ctx.role)) {
    throw new Error('Only owners and coordinators can revoke access.');
  }

  await withUserTx(ctx.userId, async (tx) => {
    await assertRestrictedDocument(tx, ctx.circleId, documentId);
    await tx
      .delete(schema.restrictedDocumentGrants)
      .where(
        and(
          eq(schema.restrictedDocumentGrants.documentId, documentId),
          eq(schema.restrictedDocumentGrants.userId, userId),
        ),
      );
  });

  await bumpCircleVersion(ctx.circleId);
}

/**
 * Who has access (grants) and who has opened the document (access log).
 * Owner and coordinator only.
 */
export async function listViewers(circleId: string, documentId: string) {
  const ctx = await requireCircleRole(circleId, GRANT_ROLES);

  return withUserTx(ctx.userId, async (tx) => {
    const grants = await tx
      .select({
        userId: schema.restrictedDocumentGrants.userId,
        fullName: schema.users.fullName,
        grantedAt: schema.restrictedDocumentGrants.createdAt,
      })
      .from(schema.restrictedDocumentGrants)
      .innerJoin(schema.users, eq(schema.restrictedDocumentGrants.userId, schema.users.id))
      .where(eq(schema.restrictedDocumentGrants.documentId, documentId))
      .orderBy(schema.users.fullName);

    const views = await tx
      .select({
        userId: schema.documentAccessLog.userId,
        fullName: schema.users.fullName,
        action: schema.documentAccessLog.action,
        accessedAt: schema.documentAccessLog.accessedAt,
      })
      .from(schema.documentAccessLog)
      .innerJoin(schema.users, eq(schema.documentAccessLog.userId, schema.users.id))
      .where(
        and(
          eq(schema.documentAccessLog.documentId, documentId),
          eq(schema.documentAccessLog.circleId, circleId),
        ),
      )
      .orderBy(desc(schema.documentAccessLog.accessedAt))
      .limit(50);

    return { grants, views };
  });
}

/**
 * Asks the database whether the user may view the document (SQL function can_view_document).
 * Used by the signed-URL route, which has no circle id in its path.
 */
export async function canViewDocument(userId: string, documentId: string): Promise<boolean> {
  const result = await withUserTx(userId, (tx) =>
    tx.execute<{ ok: boolean }>(sql`SELECT can_view_document(${documentId}::uuid) AS ok`),
  );
  return result.rows[0]?.ok === true;
}

/** Returns the storage pathname and circle for a document the user can view, or null. */
export async function getDocumentBlobRef(userId: string, documentId: string) {
  const rows = await withUserTx(userId, (tx) =>
    tx
      .select({
        circleId: schema.documents.circleId,
        blobPathname: schema.documents.blobPathname,
      })
      .from(schema.documents)
      .where(and(eq(schema.documents.id, documentId), isNull(schema.documents.deletedAt)))
      .limit(1),
  );
  return rows[0] ?? null;
}

/** Appends a row to the append-only document access log. */
export async function logDocumentAccess(
  userId: string,
  documentId: string,
  circleId: string,
  action: 'viewed' = 'viewed',
): Promise<void> {
  await withUserTx(userId, (tx) =>
    tx.insert(schema.documentAccessLog).values({ documentId, circleId, userId, action }),
  );
}
